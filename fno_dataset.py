"""
# PDE Solver
This section solves a nonlinear PDE problem using FEniCS to model the mechanical response of a material under applied traction.
First, we define a Dirichlet boundary condition on the left side of the mesh, constraining the displacement field u to zero. 
The vector function space V is used to represent displacement fields, while scalar function space S is used to project the precomputed elasticity field (E_f)
into compatible function spaces. We then define the kinematic quantities: the deformation gradient F, the Right Cauchy–Green tensor C, 
and scalar invariants such as the determinant J_invariant, first invariant (I1), and second invariant (I2). 
These quantities are used to construct the strain energy density function psi based on a Mooney–Rivlin hyperelastic material model, which captures nonlinear elasticity.


Next, we introduce a traction expression to apply external forces on the right boundary of the domain, representing a constant mechanical load.
The total potential energy functional Pi is formed as the sum of the strain energy over the domain minus the work done by the applied traction.
The weak form F of the problem is derived by differentiating Pi with respect to the displacement field,
and its Jacobian J is computed for use in the Newton solver. A NonlinearVariationalSolver is then configured with appropriate tolerances and solver settings
(Newton method with MUMPS linear solver) to iteratively find the displacement field u that satisfies equilibrium. If convergence is successful, we obtain a
numerical solution representing the material’s deformed configuration under the given load, which can then be used for further analysis or dataset generation
for training the FNO model.
"""

#PDE solver
param_c = 10
tolerance = 1e-6#1e-15
left = df.CompiledSubDomain("near(x[0], side) && on_boundary", side=0.0, tol=tolerance)
S = E_f.function_space()  # Get the scalar function space of E_f
V = df.VectorFunctionSpace(mesh, "Lagrange", 2)
c = df.Expression(("0.0", "0.0"), degree=2)
# Apply Dirichlet boundary condition on the left side
bcs = df.DirichletBC(V, c, left)

# Define functions
du = df.TrialFunction(V)  # Incremental displacement
v = df.TestFunction(V)  # Test function
u = df.Function(V)  # Displacement from previous iteration


D = mesh.topology().dim()
neumann_domain = df.MeshFunction("size_t", mesh, D - 1)
neumann_domain.set_all(0)
df.CompiledSubDomain("near(x[0], side) && on_boundary", side=L, tol=tolerance).mark(neumann_domain, 1)
ds = df.Measure("ds", subdomain_data=neumann_domain)


# Kinematics
d_dim = u.geometric_dimension()
I = df.Identity(d_dim)  # Identity tensor
# requires vector
deformation_gradient = I + df.grad(u)  # Deformation gradient
Cauchy_tensor = deformation_gradient.T * deformation_gradient  # Right Cauchy-Green tensor


c  = df.Constant(param_c)
c1 = df.project(E_f / 4, S)  # Project E_f/4 into the same function space
c2 = df.project(E_f / 8, S)  # Project E_f/8 into the same function space
d = df.Constant(100.0) # d = 2 * (c1 + 2 * c2)



# Invariants
J_invariant = df.det(deformation_gradient)
I1 = df.tr(Cauchy_tensor)
I2 = 0.5 * (I1 ** 2 - df.tr(Cauchy_tensor * Cauchy_tensor))
# Stored strain energy density, energy type = mooneyrivlin
psi = c * (J_invariant - 1)**2 - d * df.ln(J_invariant) + c1 * (I1 - 2) + c2 * (I2 - 1)


class TractionExpression0(df.UserExpression):  # Constant traction on both x, y components
      def eval(self, value, _x):
          value[0] = 1e2
          value[1] = 1e3
t = TractionExpression0(degree=2, element=V.ufl_element())

start_time = time.time()
#dot requires non-scalar arguments
#solve
u.vector()[:] = 0
Pi = psi * df.dx - df.dot(t, u) * ds(1)
F = df.derivative(Pi, u, v)
J = df.derivative(F, u, du)
problem = df.NonlinearVariationalProblem(F, u, bcs, J)
solver = df.NonlinearVariationalSolver(problem)
prm = solver.parameters
prm["newton_solver"]["absolute_tolerance"] = 1E-6
prm["newton_solver"]["relative_tolerance"] = 1E-7
prm["newton_solver"]["maximum_iterations"] = 50
prm["newton_solver"]["relaxation_parameter"] = 0.8
prm["newton_solver"]["linear_solver"] = "mumps"
prm["newton_solver"]["error_on_nonconvergence"] = False
try:
    solver.solve()
    print("Successfully converged!")
except RuntimeError as e:
    print(f"Solver failed: {e}")
    print("Try load stepping or reduce material parameters")
print("Running time = %.3f" % float(time.time() - start_time))

"""
After solving the PDE with FEniCS and obtaining the displacement field u, this code maps the FEniCS solution back onto a regular Cartesian grid.
First, we recreate the same grid used for interpolation to ensure consistency with the original dataset dimensions. We then define a helper function,
evaluate_displacement, which queries the FEniCS solution u at any given point (x, y) and returns the displacement components. To efficiently evaluate
the solution across all grid points, we vectorize this function using numpy.vectorize and apply it to the entire meshgrid. The resulting arrays, disp_x_exact
and disp_y_exact, contain the x- and y-components of the displacement at every grid point, providing a structured representation of the PDE solution suitable
for visualization, analysis, or use as training data for the FNO model.
"""

# Get the grid dimensions (should match your E_field)
Ny, Nx = E_field.shape

# Recreate the same grid you used for interpolation
x_grid = np.linspace(0, L, Nx)
y_grid = np.linspace(0, 1.0, Ny)  # End at 1.0 as requested
X_grid, Y_grid = np.meshgrid(x_grid, y_grid)

# Method 1: Vectorized evaluation using numpy.vectorize
def evaluate_displacement(x, y):
    """Evaluate FEniCS displacement function at point (x, y)"""
    try:
        # u(x, y) returns the displacement vector at point (x, y)
        point_displacement = u(x, y)
        return float(point_displacement[0]), float(point_displacement[1])
    except:
        return np.nan, np.nan

# Vectorize the function for efficient evaluation
u_vectorized = np.vectorize(evaluate_displacement)

# Calculate displacements for all grid points at once
disp_x_exact, disp_y_exact = u_vectorized(X_grid, Y_grid)

