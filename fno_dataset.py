"""
#Interpolating Field Data onto a FEniCS Mesh

In this step, we take field data defined on a regular Cartesian grid (E_field) and map it onto the unstructured FEniCS mesh. 
This is done using interpolation, which estimates field values at arbitrary mesh points based on known values from the grid. 
Specifically, we use SciPy’s RegularGridInterpolator with linear interpolation, which works by locating the grid cell surrounding each
mesh point and computing a weighted average of the four nearest grid values. This produces a smooth approximation of the field on the mesh, 
even if the mesh nodes do not align with the original grid. The result is a FEniCS Function (E_f) that represents the same field data but is 
now compatible with FEniCS solvers for further PDE computations.
"""

from scipy.interpolate import griddata, RegularGridInterpolator
"""
E_field: 2D numpy array (ny, nx)
x_coords: 1D array of x coordinates
y_coords: 1D array of y coordinates
mesh: FEniCS mesh using NumPy Interpolation
"""
Ny, Nx = E_field.shape
# Create function space and function
